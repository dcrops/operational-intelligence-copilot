"""AppTests for executive summary rendering and narrative provider controls."""

from __future__ import annotations

import pytest

from tests.app.golden_expectations import (
    SECTION_EXECUTIVE_SUMMARY,
    get_scenario,
)
from tests.app.helpers import (
    assert_direct_answer,
    assert_executive_reasoning,
    assert_generation_method_visible,
    assert_narrative_content_visible,
    assert_narrative_placeholder_hidden,
    assert_provider_status_visible,
    assert_section_visible,
    assert_transparency,
    ask_question,
    launch_app,
    load_sample_dataset,
    run_analysis,
    select_narrative_mode,
    sidebar_visible_text,
    user_visible_text,
)
from ui.narrative_runtime import (
    NARRATIVE_MODE_DETERMINISTIC,
    NARRATIVE_MODE_OPENAI,
)

pytestmark = [pytest.mark.app, pytest.mark.streamlit, pytest.mark.ui]


def _enable_deterministic_narrative_env(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("OIC_NARRATIVE_ENABLED", "true")
    monkeypatch.setenv("OIC_NARRATIVE_PROVIDER", "deterministic")


class TestExecutiveSummaryDefaultProvider:
    def test_default_provider_renders_executive_summary(self, app) -> None:
        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)

        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_section_visible(app, SECTION_EXECUTIVE_SUMMARY)
        assert_narrative_content_visible(app)
        assert_generation_method_visible(app, "Deterministic Engine")
        assert "Generated By" in user_visible_text(app)
        assert "Generation Time:" in user_visible_text(app)
        assert_direct_answer(app)


class TestNarrativeRenderingEnabled:
    def test_deterministic_provider_renders_executive_summary(self, app) -> None:
        select_narrative_mode(app, NARRATIVE_MODE_DETERMINISTIC)
        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)

        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_narrative_placeholder_hidden(app)
        assert_section_visible(app, SECTION_EXECUTIVE_SUMMARY)
        assert_narrative_content_visible(app)
        assert_generation_method_visible(app, "Deterministic Engine")

    def test_deterministic_sections_preserved_when_narrative_enabled(self, app) -> None:
        select_narrative_mode(app, NARRATIVE_MODE_DETERMINISTIC)
        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)

        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_narrative_placeholder_hidden(app)
        assert_direct_answer(app)
        assert_executive_reasoning(app)
        assert_transparency(app)
        assert_narrative_content_visible(app)

    def test_env_default_still_enables_deterministic_mode(
        self,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        _enable_deterministic_narrative_env(monkeypatch)

        app = launch_app()
        assert app.session_state["narrative_mode"] == NARRATIVE_MODE_DETERMINISTIC

        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)
        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_narrative_placeholder_hidden(app)
        assert_narrative_content_visible(app)


class TestNarrativeRuntimeControls:
    def test_sidebar_offers_only_two_providers(self, app) -> None:
        radio = app.sidebar.radio(key="narrative_mode")
        assert radio is not None
        assert len(radio.options) == 2
        sidebar = sidebar_visible_text(app)
        assert "Deterministic Engine" in sidebar
        assert "OpenAI GPT" in sidebar
        assert "Disabled" not in sidebar
        assert radio.label == "Narrative Provider"

    def test_provider_status_shows_deterministic_engine_without_analysis(self, app) -> None:
        select_narrative_mode(app, NARRATIVE_MODE_DETERMINISTIC)
        assert_provider_status_visible(app, "Deterministic Engine")

    def test_ui_overrides_disabled_environment(
        self,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        monkeypatch.setenv("OIC_NARRATIVE_ENABLED", "false")

        app = launch_app()
        select_narrative_mode(app, NARRATIVE_MODE_DETERMINISTIC)

        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)
        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_narrative_placeholder_hidden(app)
        assert_narrative_content_visible(app)

    def test_openai_mode_without_api_key_falls_back_cleanly(self, app) -> None:
        select_narrative_mode(app, NARRATIVE_MODE_OPENAI)
        assert_provider_status_visible(app, "OpenAI GPT unavailable")

        scenario = get_scenario("manufacturing_bootstrap_smoke")
        load_sample_dataset(app, scenario.dataset.sidebar_label)
        ask_question(app, scenario.question.question)
        run_analysis(app)

        assert_narrative_placeholder_hidden(app)
        assert_narrative_content_visible(app)
        assert_generation_method_visible(app, "Fallback to Deterministic Engine")
        assert "Generation Time:" in user_visible_text(app)
        assert any(
            "OpenAI mode selected but no API key was found" in (warning.value or "")
            for warning in app.warning
        )
