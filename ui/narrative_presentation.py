"""Pure presentation helpers for executive narrative in the UI."""

from __future__ import annotations

from src.operational_intelligence.llm.narrative_config import PROVIDER_OPENAI
from src.operational_intelligence.llm.narrative_models import (
    AssessmentConfidencePresentation,
    ExecutiveAssessmentBanner,
    NarrativeGenerationMetadata,
    NarrativeResponse,
)

EXECUTIVE_SUMMARY_HEADING = "Executive Summary"
EXECUTIVE_NARRATIVE_AI_ASSISTED_HEADING = EXECUTIVE_SUMMARY_HEADING
EXECUTIVE_ASSESSMENT_HEADING = "Executive Assessment"
ASSESSMENT_CONFIDENCE_HEADING = "Assessment Confidence"
LIMITATIONS_HEADING = "Limitations"
TECHNICAL_DETAILS_HEADING = "Technical Details"
GENERATED_BY_HEADING = "Generated By"
GENERATION_METHOD_HEADING = GENERATED_BY_HEADING

NARRATIVE_DISABLED_MESSAGE = (
    "Executive summary is unavailable for this analysis. "
    "The deterministic analysis above is the authoritative answer."
)

GOVERNANCE_CAPTION = (
    "This executive summary synthesises the deterministic analysis above "
    "and suggests where to investigate. "
    "It does not replace Direct Answer, Executive Reasoning, or System Transparency."
)

_BANNER_ACCENT_COLORS = {
    "critical": "#dc2626",
    "high": "#ea580c",
    "medium": "#ca8a04",
    "low": "#16a34a",
    "stable": "#16a34a",
}


def format_executive_assessment_banner(banner: ExecutiveAssessmentBanner) -> str:
    """Return markdown with severity accent styling for the executive assessment banner."""
    accent = _BANNER_ACCENT_COLORS.get(banner.level.lower(), "#64748b")
    indicator = banner.indicator.strip()
    headline = banner.headline.strip()
    return (
        f'<div style="border-left: 4px solid {accent}; padding: 0.75rem 1rem; '
        f'margin: 0.5rem 0 1rem 0; background-color: rgba(148, 163, 184, 0.08);">'
        f"<strong>{indicator} {EXECUTIVE_ASSESSMENT_HEADING}</strong><br><br>"
        f"{headline}"
        f"</div>"
    )


def format_assessment_confidence_level(
    confidence: AssessmentConfidencePresentation,
) -> str:
    """Return a compact confidence level line with optional indicator."""
    indicator = confidence.indicator.strip()
    level = confidence.level.strip()
    if indicator:
        return f"{indicator} **{level}**"
    return f"**{level}**"


def format_generation_method(
    metadata: NarrativeGenerationMetadata,
) -> tuple[str, str]:
    """Return (status_level, label) for backend-driven provider display."""
    if metadata.fallback_used:
        return ("warning", "Fallback to Deterministic Engine")

    if metadata.actual_provider == PROVIDER_OPENAI:
        return ("active", metadata.generator_name)

    return ("active", metadata.generator_name)


def format_generated_by_secondary_metadata(
    metadata: NarrativeGenerationMetadata,
) -> tuple[str, ...]:
    """Return secondary metadata lines shown beneath the Generated By provider label."""
    lines: list[str] = []
    if metadata.model is not None:
        lines.append(f"Model: {metadata.model}")
    if metadata.wall_clock_duration_ms is not None:
        lines.append(f"Generation Time: {metadata.wall_clock_duration_ms} ms")
    return tuple(lines)


def format_generation_details(narrative: NarrativeResponse) -> tuple[str, ...]:
    """Return caption-ready generation detail lines for available metadata only."""
    metadata = narrative.generation_metadata
    lines: list[str] = []

    if metadata is not None:
        lines.append(f"Requested provider: {metadata.requested_provider}")
        lines.append(f"Actual provider: {metadata.actual_provider}")
        lines.append(f"Generator: {metadata.generator_name}")
        if metadata.fallback_used:
            lines.append("Fallback used: yes")
            if metadata.fallback_reason:
                lines.append(f"Fallback reason: {metadata.fallback_reason}")
        if metadata.model is not None:
            lines.append(f"Model: {metadata.model}")
        if metadata.wall_clock_duration_ms is not None:
            lines.append(f"Generation Time: {metadata.wall_clock_duration_ms} ms")
        if metadata.provider_version is not None:
            lines.append(f"Provider version: {metadata.provider_version}")
        return tuple(lines)

    if narrative.generator_type:
        lines.append(f"Generator: {narrative.generator_type}")

    if narrative.model is not None:
        lines.append(f"Model: {narrative.model}")

    if narrative.generation_duration_ms is not None:
        lines.append(f"Generation Time: {narrative.generation_duration_ms} ms")

    if narrative.artifact_version is not None:
        lines.append(f"Provider version: {narrative.artifact_version}")

    return tuple(lines)
